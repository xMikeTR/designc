const { test } = require('node:test');
const assert = require('node:assert/strict');
const Core = require('../renderer/core.js');

const DSL = `workspace "Q" {
  model {
    s = softwareSystem "Quotes" {
      ui = container "Quote UI" {
        tags "UI"
      }
      portal = container "Portal" {
        tags "UI"
      }
      api = container "Quotes API"
      other = container "Other"
    }
    ui -> api "calls" {
      properties {
        d.interaction "sync"
      }
    }
    portal -> other "calls" {
      properties {
        d.interaction "sync"
      }
    }
  }
}
`;
const crit = (id, element, extra = {}) => ({ id, requirement: 'R-1', element, _path: `acceptance/${id}.yaml`, _text: `id: ${id}\n`, states: ['ready'],
  locators: { save: { role: 'button', name: 'Save "quote"' }, email: { role: 'label', name: 'Email' } },
  cases: [{ state: 'ready', given: 'a quote\nin draft', when: 'the user saves', then: 'it is saved', uses: ['save', 'email'] }, { state: 'ready', given: 'x', then: 'y' }], ...extra });

test('one deterministic spec per criterion, written under tests/acceptance/<element>/', () => {
  const model = Core.parse(DSL);
  const r = Core.acceptanceSpecs({ model, criteria: [crit('AC-1', 'Quotes/Quote UI')] });
  assert.equal(r.loop, null);
  assert.equal(r.files.length, 1);
  assert.equal(r.files[0].path, 'tests/acceptance/quotes-quote-ui/AC-1.spec.ts');
  const t = r.files[0].text;
  assert.match(t, /^\/\/ GENERATED by designc from acceptance\/AC-1\.yaml \(hash [0-9a-f]{16}\)\. Do not edit/);
  assert.match(t, /test\("ready", async/);
  assert.match(t, /test\("ready \(2\)", async/);
  assert.match(t, /page\.getByRole\("button", \{ name: "Save \\"quote\\"" \}\)/);
  assert.match(t, /page\.getByLabel\("Email"\)/);
  assert.match(t, /\/\/ given: a quote in draft/, 'newlines never leave a comment');
  assert.equal(Core.acceptanceSpecs({ model, criteria: [crit('AC-1', 'Quotes/Quote UI')] }).files[0].text, t, 'deterministic');
});

test('the loop runs the in-scope specs and those of their callers; the rest wait for the merge', () => {
  const model = Core.parse(DSL);
  const criteria = [crit('AC-1', 'Quotes/Quote UI'), crit('AC-2', 'Quotes/Portal')];
  const r = Core.acceptanceSpecs({ model, criteria, inScope: ['Quotes API'] });
  assert.deepEqual(r.loop, ['tests/acceptance/quotes-quote-ui/AC-1.spec.ts']);
  assert.equal(r.files.length, 2);
});

test('handoverPlan carries the specs: listed, hashed, outside the id', () => {
  const model = { path: 'model/workspace.dsl', text: DSL };
  const specs = Core.acceptanceSpecs({ model: Core.parse(DSL), criteria: [crit('AC-1', 'Quotes/Quote UI')], inScope: ['Quote UI'] });
  const base = { date: '2026-10-12', now: 'n', by: 'm', model };
  const a = Core.handoverPlan({ ...base });
  const b = Core.handoverPlan({ ...base, specs });
  assert.equal(a.id, b.id);
  const yaml = b.files[0].text;
  assert.match(yaml, /specs: \["tests\/acceptance\/quotes-quote-ui\/AC-1\.spec\.ts"\]/);
  assert.match(yaml, /loop_specs: \["tests\/acceptance\/quotes-quote-ui\/AC-1\.spec\.ts"\]/);
  assert.ok(b.files.some(f => f.path.endsWith('tests/acceptance/quotes-quote-ui/AC-1.spec.ts')));
  assert.match(yaml, /path: "tests\/acceptance\/quotes-quote-ui\/AC-1\.spec\.ts", hash:/);
});
