#!/usr/bin/env node
/* Generates renderer/ui-schemas.js and python/designc/ui_schemas.json from docs/ui-*.schema.json, so the JS and
   Python checkers read the same schemas. `node scripts/gen-ui-schemas.js --check` exits 1 when they are stale. */
const fs = require('fs'), path = require('path');
const root = path.join(__dirname, '..');
const NAMES = ['ui-component-manifest', 'ui-template', 'ui-screen-spec', 'ui-holdout'];
const docs = {};
for (const n of NAMES) docs[`${n}.schema.json`] = JSON.parse(fs.readFileSync(path.join(root, 'docs', `${n}.schema.json`), 'utf8'));
const js = `/* GENERATED by scripts/gen-ui-schemas.js from docs/ui-*.schema.json. Do not edit. */\nconst UiSchemas = ${JSON.stringify(docs, null, 1)};\nif (typeof module !== 'undefined') module.exports = UiSchemas;\n`;
const py = JSON.stringify(docs, null, 1) + '\n';
const targets = [[path.join(root, 'renderer', 'ui-schemas.js'), js], [path.join(root, 'python', 'designc', 'ui_schemas.json'), py]];
if (process.argv.includes('--check')) {
  const stale = targets.filter(([f, t]) => !fs.existsSync(f) || fs.readFileSync(f, 'utf8') !== t).map(([f]) => path.relative(root, f));
  if (stale.length) { console.error(`stale: ${stale.join(', ')}. Run node scripts/gen-ui-schemas.js`); process.exit(1); }
} else for (const [f, t] of targets) fs.writeFileSync(f, t);
