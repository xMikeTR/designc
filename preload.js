// The only bridge between the UI and the machine. Everything is scoped to the open folder by main.js.
const { contextBridge, ipcRenderer } = require('electron');
const on = (ch, fn) => { const h = (_e, ...a) => fn(...a); ipcRenderer.on(ch, h); return () => ipcRenderer.removeListener(ch, h); };
contextBridge.exposeInMainWorld('host', {
  boot: () => ipcRenderer.invoke('app:boot'),
  openFolder: () => ipcRenderer.invoke('folder:open'),
  openPath: p => ipcRenderer.invoke('folder:openPath', p),
  openSample: () => ipcRenderer.invoke('folder:sample'),
  tree: () => ipcRenderer.invoke('fs:tree'),
  read: rel => ipcRenderer.invoke('fs:read', rel),
  exists: rel => ipcRenderer.invoke('fs:exists', rel),
  write: (rel, text) => ipcRenderer.invoke('fs:write', rel, text),
  list: (dir, ext) => ipcRenderer.invoke('fs:list', dir, ext),
  appendLedgerEvent: ev => ipcRenderer.invoke('ledger:event', ev),
  runCheck: (id, cmd) => ipcRenderer.invoke('check:run', id, cmd),
  cancelCheck: id => ipcRenderer.invoke('check:cancel', id),
  chat: messages => ipcRenderer.invoke('llm:chat', messages),
  chooseCodebase: () => ipcRenderer.invoke('codebase:choose'),
  extract: p => ipcRenderer.invoke('codebase:extract', p),
  readCode: (p, rel) => ipcRenderer.invoke('codebase:read', p, rel),
  telemetry: () => ipcRenderer.invoke('telemetry:fetch'),
  agentChat: (id, payload) => ipcRenderer.invoke('agent:chat', id, payload),
  agentCancel: id => ipcRenderer.invoke('agent:cancel', id),
  searchCode: (p, q, max) => ipcRenderer.invoke('codebase:search', p, q, max),
  onAgentDelta: fn => on('agent:delta', fn),
  acpAgents: () => ipcRenderer.invoke('acp:agents'),
  acpConnect: (key, meta) => ipcRenderer.invoke('acp:connect', key, meta),
  acpPrompt: (key, text) => ipcRenderer.invoke('acp:prompt', key, text),
  acpCancel: key => ipcRenderer.invoke('acp:cancel', key),
  acpDisconnect: key => ipcRenderer.invoke('acp:disconnect', key),
  onAcp: (ch, fn) => on(ch, fn),
  aguiAgents: () => ipcRenderer.invoke('agui:agents'),
  aguiRun: (id, key, body) => ipcRenderer.invoke('agui:run', id, key, body),
  aguiCancel: id => ipcRenderer.invoke('agui:cancel', id),
  onUiCall: fn => on('ui:call', fn),
  uiReply: (id, value) => ipcRenderer.invoke('ui:reply', id, value),
  onCmd: fn => on('cmd', fn),
  onChanged: fn => on('fs:changed', fn),
  onFolder: fn => on('folder:opened', fn),
  onCheckOutput: fn => on('check:output', fn),
});
