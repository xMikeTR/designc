// The only bridge between the UI and the machine. Everything is scoped to the open folder by main.js.
const { contextBridge, ipcRenderer } = require('electron');
const on = (ch, fn) => { const h = (_e, ...a) => fn(...a); ipcRenderer.on(ch, h); return () => ipcRenderer.removeListener(ch, h); };
contextBridge.exposeInMainWorld('host', {
  boot: () => ipcRenderer.invoke('app:boot'),
  openFolder: () => ipcRenderer.invoke('folder:open'),
  openPath: p => ipcRenderer.invoke('folder:openPath', p),
  openSample: () => ipcRenderer.invoke('folder:sample'),
  openGuide: () => ipcRenderer.invoke('app:guide'),
  tree: () => ipcRenderer.invoke('fs:tree'),
  read: rel => ipcRenderer.invoke('fs:read', rel),
  exists: rel => ipcRenderer.invoke('fs:exists', rel),
  parityShot: sha => ipcRenderer.invoke('parity:shot', sha),
  write: (rel, text) => ipcRenderer.invoke('fs:write', rel, text),
  remove: rel => ipcRenderer.invoke('fs:remove', rel),
  list: (dir, ext) => ipcRenderer.invoke('fs:list', dir, ext),
  gitStatus: () => ipcRenderer.invoke('git:status'),
  gitTrust: () => ipcRenderer.invoke('git:trust'),
  gitRefs: () => ipcRenderer.invoke('git:refs'),
  gitLog: (rel, max) => ipcRenderer.invoke('git:log', rel, max),
  gitShow: (hash, rel) => ipcRenderer.invoke('git:show', hash, rel),
  gitStage: paths => ipcRenderer.invoke('git:stage', paths),
  gitUnstage: paths => ipcRenderer.invoke('git:unstage', paths),
  gitDiscard: paths => ipcRenderer.invoke('git:discard', paths),
  gitCommit: message => ipcRenderer.invoke('git:commit', message),
  gitBranch: name => ipcRenderer.invoke('git:branch', name),
  gitSwitch: name => ipcRenderer.invoke('git:switch', name),
  gitFetch: () => ipcRenderer.invoke('git:fetch'),
  gitPull: () => ipcRenderer.invoke('git:pull'),
  gitPush: () => ipcRenderer.invoke('git:push'),
  gitPublish: () => ipcRenderer.invoke('git:publish'),
  gitStashPush: message => ipcRenderer.invoke('git:stashPush', message),
  gitStashList: () => ipcRenderer.invoke('git:stashList'),
  gitStashApply: ref => ipcRenderer.invoke('git:stashApply', ref),
  gitStashPop: () => ipcRenderer.invoke('git:stashPop'),
  gitStashDrop: ref => ipcRenderer.invoke('git:stashDrop', ref),
  gitAttrs: () => ipcRenderer.invoke('git:attrs'),
  gitAddUnion: () => ipcRenderer.invoke('git:addUnion'),
  appendLedgerEvent: ev => ipcRenderer.invoke('ledger:event', ev),
  runCheck: (id, cmd) => ipcRenderer.invoke('check:run', id, cmd),
  workHead: rel => ipcRenderer.invoke('work:head', rel),
  workOnMain: (rel, commit) => ipcRenderer.invoke('work:onMain', rel, commit),
  workRun: (id, rel, cmd) => ipcRenderer.invoke('work:run', id, rel, cmd),
  depsCheck: () => ipcRenderer.invoke('deps:check'),
  depsInstall: id => ipcRenderer.invoke('deps:install', id),
  cancelCheck: id => ipcRenderer.invoke('check:cancel', id),
  chat: messages => ipcRenderer.invoke('llm:chat', messages),
  setupEnv: names => ipcRenderer.invoke('setup:env', names),
  setupAdc: () => ipcRenderer.invoke('setup:adc'),
  setupTest: (kind, draft) => ipcRenderer.invoke('setup:test', kind, draft),
  registries: () => ipcRenderer.invoke('registry:keys'),
  registryRead: (key, rel) => ipcRenderer.invoke('registry:read', key, rel),
  registryList: (key, dir, ext) => ipcRenderer.invoke('registry:list', key, dir, ext),
  chooseCodebase: () => ipcRenderer.invoke('codebase:choose'),
  chooseImportFolder: () => ipcRenderer.invoke('import:choose'),
  readImportFolder: p => ipcRenderer.invoke('import:read', p),
  extract: p => ipcRenderer.invoke('codebase:extract', p),
  readCode: (p, rel) => ipcRenderer.invoke('codebase:read', p, rel),
  telemetry: () => ipcRenderer.invoke('telemetry:fetch'),
  telemetryTrace: (traceId, spanId) => ipcRenderer.invoke('telemetry:trace', traceId, spanId),
  agentChat: (id, payload) => ipcRenderer.invoke('agent:chat', id, payload),
  agentCancel: id => ipcRenderer.invoke('agent:cancel', id),
  searchCode: (p, q, max) => ipcRenderer.invoke('codebase:search', p, q, max),
  onAgentDelta: fn => on('agent:delta', fn),
  acpAgents: () => ipcRenderer.invoke('acp:agents'),
  acpConnect: (key, meta) => ipcRenderer.invoke('acp:connect', key, meta),
  acpPrompt: (key, text) => ipcRenderer.invoke('acp:prompt', key, text),
  acpCancel: key => ipcRenderer.invoke('acp:cancel', key),
  acpDisconnect: key => ipcRenderer.invoke('acp:disconnect', key),
  onAcp: (ch, fn) => on(ch, fn),
  aguiAgents: () => ipcRenderer.invoke('agui:agents'),
  aguiRun: (id, key, body) => ipcRenderer.invoke('agui:run', id, key, body),
  aguiCancel: id => ipcRenderer.invoke('agui:cancel', id),
  onUiCall: fn => on('ui:call', fn),
  uiReply: (id, value) => ipcRenderer.invoke('ui:reply', id, value),
  onCmd: fn => on('cmd', fn),
  termOpen: (cols, rows) => ipcRenderer.invoke('term:open', cols, rows),
  termInput: (id, s) => ipcRenderer.invoke('term:input', id, s),
  termResize: (id, cols, rows) => ipcRenderer.invoke('term:resize', id, cols, rows),
  termClose: id => ipcRenderer.invoke('term:close', id),
  onTermData: fn => on('term:data', fn),
  onTermExit: fn => on('term:exit', fn),
  onChanged: fn => on('fs:changed', fn),
  onFolder: fn => on('folder:opened', fn),
  onCheckOutput: fn => on('check:output', fn),
});
